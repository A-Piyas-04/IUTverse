// Generates docs/api/endpoint-inventory.md from the bundled contract.
//   node scripts/contract/inventory.mjs           write the file
//   node scripts/contract/inventory.mjs --check   fail when the committed file is stale
import fs from "node:fs";
import path from "node:path";
import { authOf, loadSpec, operations, root } from "./spec.mjs";

const target = path.join(root, "docs/api/endpoint-inventory.md");
const spec = loadSpec();
const ops = operations(spec);

const count = (key, value) => ops.filter(({ op }) => op[key] === value).length;
const bodyOf = (op) => Object.keys(op.requestBody?.content ?? {}).map((type) => (type === "application/json" ? "json" : type === "multipart/form-data" ? "multipart" : type));
const flags = (op) => {
  const list = [];
  if ((op.parameters ?? []).some((p) => p.name === "page" || (p.$ref ?? "").endsWith("/Page"))) list.push("paginated");
  if (bodyOf(op).includes("multipart")) list.push("upload");
  if (Object.values(op.responses ?? {}).some((r) => r?.headers?.Location)) list.push("redirect");
  return list.join(", ") || "-";
};
const authLabel = (op) => {
  const auth = authOf(op);
  const role = op["x-required-role"]?.join("/");
  return auth === "required" ? (role ? `member, ${role}` : "member") : auth === "optional" ? "optional" : "public";
};

const lines = [];
lines.push("<!-- GENERATED by `npm run contract:inventory` from docs/api/openapi.yaml. Do not edit. -->", "");
lines.push("# Endpoint inventory", "");
lines.push(`Contract version **${spec.info.version}**, ${ops.length} operations over ${Object.keys(spec.paths).length} paths.`, "");
lines.push("| Priority | Operations | Verified | Reviewed | Inferred |", "|---|---|---|---|---|");
for (const priority of ["P0", "P1", "other"]) {
  const subset = ops.filter(({ op }) => op["x-priority"] === priority);
  const by = (status) => subset.filter(({ op }) => op["x-contract-status"] === status).length;
  lines.push(`| ${priority} | ${subset.length} | ${by("verified")} | ${by("reviewed")} | ${by("inferred")} |`);
}
lines.push("", `Totals by contract status: verified ${count("x-contract-status", "verified")}, reviewed ${count("x-contract-status", "reviewed")}, inferred ${count("x-contract-status", "inferred")}.`, "");
lines.push("- **verified**: a conformance test runs the real handler and validates the response against this contract.");
lines.push("- **reviewed**: the schema was derived by reading the handler; no test pins it yet.");
lines.push("- **inferred**: status codes and field names were scanned from the handler; body schemas are loose.", "");
lines.push("Authorization shown is what the route pipeline enforces (`authenticateToken`, `optionalAuth`, `requireAdmin`, `requireRole`). Ownership checks inside handlers are not listed.", "");

for (const priority of ["P0", "P1", "other"]) {
  lines.push(`## ${priority}`, "", "| Operation | Method | Path | Auth | Request | Success | Flags | Status | Source |", "|---|---|---|---|---|---|---|---|---|");
  const subset = ops
    .filter(({ op }) => op["x-priority"] === priority)
    .sort((a, b) => a.route.localeCompare(b.route) || a.method.localeCompare(b.method));
  for (const { route, method, op } of subset) {
    const success = Object.keys(op.responses).filter((code) => /^[23]/.test(code)).join("/");
    const source = (op["x-source"] ?? "").split(" -> ")[0];
    lines.push(`| \`${op.operationId}\` | ${method} | \`${route}\` | ${authLabel(op)} | ${bodyOf(op).join(", ") || "-"} | ${success} | ${flags(op)} | ${op["x-contract-status"]} | \`${source}\` |`);
  }
  lines.push("");
}

const text = lines.join("\n");
if (process.argv.includes("--check")) {
  const committed = fs.existsSync(target) ? fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n") : null;
  if (committed !== text) {
    console.error("docs/api/endpoint-inventory.md is out of date. Run `npm run contract:inventory` and commit the result.");
    process.exit(1);
  }
  console.log("endpoint inventory is up to date");
} else {
  fs.writeFileSync(target, text);
  console.log(`wrote ${path.relative(root, target)}`);
}
