// Bundles the split OpenAPI sources in docs/api/src into the single committed contract, docs/api/openapi.yaml.
//
//   node scripts/contract/build.mjs           write docs/api/openapi.yaml
//   node scripts/contract/build.mjs --check   fail when the committed file is stale (CI drift check)
//
// The bundle is deterministic: same sources, same bytes. Line endings are normalized to LF so the check
// passes on Windows checkouts too.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const redocly = path.join(root, "node_modules/@redocly/cli/bin/cli.js");
const source = "docs/api/src/openapi.src.yaml";
const target = path.join(root, "docs/api/openapi.yaml");
const HEADER = "# GENERATED by `npm run contract:build` from docs/api/src. Do not edit this file; edit the sources.\n";

const tmp = path.join(os.tmpdir(), `iutverse-openapi-${process.pid}.yaml`);
try {
  execFileSync(process.execPath, [redocly, "bundle", source, "--config", "docs/api/redocly.yaml", "--output", tmp], {
    cwd: root,
    stdio: ["ignore", "ignore", "inherit"],
  });
  const bundled = HEADER + fs.readFileSync(tmp, "utf8").replace(/\r\n/g, "\n");

  if (process.argv.includes("--check")) {
    const committed = fs.existsSync(target) ? fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n") : null;
    if (committed !== bundled) {
      console.error("docs/api/openapi.yaml is out of date with docs/api/src. Run `npm run contract:build` and commit the result.");
      process.exit(1);
    }
    console.log("contract bundle is up to date");
  } else {
    fs.writeFileSync(target, bundled);
    console.log(`wrote ${path.relative(root, target)}`);
  }
} finally {
  fs.rmSync(tmp, { force: true });
}
